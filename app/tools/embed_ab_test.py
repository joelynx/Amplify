"""A/B test of embedding prompts for "find problems that share a technique".

Builds a fixed pool of questions whose stored solution names exactly one
technique (pigeonhole, generating function, martingale, ...), embeds the pool
under several prompt variants with the same model as reembed.py, and reports
precision@10 for same-technique neighbours (overall and restricted to other
sources), plus how much "has a generated solution" leaks into the vectors.

Costs about 0.5 USD for the default pool (see --dry-run for the token count).
Embeddings are cached in app/data/appdata/embed_ab_cache.json, so re-running
with a new variant only pays for that variant.

Usage (repo root, GOOGLE_API_KEY in .env.local):
  python -m app.tools.embed_ab_test --dry-run           # pool size + token estimate, no API calls
  python -m app.tools.embed_ab_test                     # run every variant, print the table
  python -m app.tools.embed_ab_test --variants current,question_only
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import random
import re
import sqlite3
import struct
import sys
import time
from collections import Counter
from pathlib import Path

import numpy as np

try:
    from dotenv import load_dotenv

    load_dotenv(".env.local")
except ImportError:
    pass

DB_PATH = Path("app/data/appdata/amplify.db")
CACHE_PATH = Path("app/data/appdata/embed_ab_cache.json")
MODEL = "models/gemini-embedding-2"
DIMENSIONS = 3072

# Exactly the prefix reembed.py uses (keep byte-identical).
CURRENT_PREFIX = (
    "Task: Find problems that share similar underlying concepts, solution techniques, and logical structures.\n\n"
)
TECHNIQUE_PREFIX = (
    "Task: Represent this problem by its mathematical structure and by the method that solves it, "
    "not by its story, objects, numbers or wording. Two problems must be close when the same technique "
    "solves both, even if one is about coins and the other about committees.\n\n"
)
# Matches both forms: \hfill [Generated by ...] (since 2026-11-03) and the old \textit{[Generated by ...]}.
ATTRIBUTION_RE = re.compile(r"\s*(?:\\hfill\s*\[Generated by [^\]]*\]|\\textit\{\[Generated by [^\]]*\]\})\s*$")

# Technique labels, matched against the stored (old) solution text.
KEYWORDS = {
    "pigeonhole": r"pigeonhole",
    "linearity of expectation": r"linearity of expectation",
    "generating function": r"generating function",
    "inclusion-exclusion": r"inclusion.exclusion",
    "cauchy-schwarz": r"cauchy.schwarz",
    "am-gm": r"am.gm",
    "markov chain": r"markov chain",
    "telescoping": r"telescop",
    "vieta": r"vieta",
    "martingale": r"martingale",
    "bayes": r"bayes",
    "chinese remainder": r"chinese remainder",
    "induction": r"by induction|induction on|inductive (?:step|hypothesis)",
    "invariant": r"\binvariant",
    "bijection": r"\bbijection",
    "extremal": r"extremal (?:principle|argument)|well.ordering",
}
PER_LABEL = 20          # pool size = PER_LABEL x labels that have enough rows
MAX_CHARS = 7000        # skip very long texts (token limit 8192 on the model)


# --- pool ---------------------------------------------------------------------

def build_pool(conn: sqlite3.Connection, per_label: int) -> list[dict]:
    rx = {k: re.compile(p, re.I) for k, p in KEYWORDS.items()}
    rows = conn.execute(
        "SELECT question_id, source, latexcode, solution, generated_solution, similarity_emb "
        "FROM questions WHERE solution IS NOT NULL AND similarity_emb IS NOT NULL ORDER BY question_id"
    ).fetchall()
    by_label: dict[str, list[dict]] = {}
    for qid, source, q, sol, gen, emb in rows:
        labels = [k for k, r in rx.items() if r.search(sol)]
        if len(labels) != 1 or len(q) + len(sol) > MAX_CHARS:
            continue
        if "includegraphics" in q or "includegraphics" in sol:
            continue
        by_label.setdefault(labels[0], []).append(
            {"qid": qid, "source": source, "question": q, "solution": sol, "generated": gen,
             "label": labels[0], "stored": emb}
        )
    rng = random.Random(42)
    pool: list[dict] = []
    for label, items in sorted(by_label.items()):
        if len(items) < per_label:
            continue
        # spread over sources: round-robin by source so one book cannot dominate a label
        rng.shuffle(items)
        buckets: dict[str, list[dict]] = {}
        for it in items:
            buckets.setdefault(it["source"], []).append(it)
        picked: list[dict] = []
        while len(picked) < per_label:
            progressed = False
            for src in sorted(buckets):
                if buckets[src] and len(picked) < per_label:
                    picked.append(buckets[src].pop())
                    progressed = True
            if not progressed:
                break
        pool.extend(picked)
    return pool


# --- variants -----------------------------------------------------------------

def text_current(it: dict) -> str:
    return (CURRENT_PREFIX + f"Question:\n{it['question']}\n\nSolution:\n{it['solution']}").strip()


def text_question_only(it: dict) -> str:
    return (CURRENT_PREFIX + f"Question:\n{it['question']}").strip()


def text_technique_prefix(it: dict) -> str:
    return (TECHNIQUE_PREFIX + f"Question:\n{it['question']}\n\nSolution:\n{it['solution']}").strip()


def text_generated(it: dict) -> str:
    """What production would embed after the re-embed: the generated solution
    where there is one (attribution line stripped), else the old one."""
    sol = ATTRIBUTION_RE.sub("", it["generated"]) if it["generated"] else it["solution"]
    return (CURRENT_PREFIX + f"Question:\n{it['question']}\n\nSolution:\n{sol}").strip()


VARIANTS: dict[str, tuple] = {
    # name: (text builder, task_type or None, note)
    "current": (text_current, None, "stored prompt: prefix + question + old solution"),
    "question_only": (text_question_only, None, "prefix + question only (no solution text)"),
    "technique_prefix": (text_technique_prefix, None, "technique-focused prefix + question + old solution"),
    "generated_solution": (text_generated, None, "prefix + question + generated solution where present"),
    # No task_type variant: the Gemini docs say gemini-embedding-2 rejects the
    # task_type field and recommends a task prefix in the text instead.
}


# --- embedding with cache -----------------------------------------------------

def load_cache() -> dict:
    if CACHE_PATH.exists():
        return json.loads(CACHE_PATH.read_text(encoding="utf-8"))
    return {}


def save_cache(cache: dict) -> None:
    CACHE_PATH.write_text(json.dumps(cache), encoding="utf-8")


def cache_key(text: str, task_type: str | None) -> str:
    return hashlib.sha256(f"{MODEL}|{task_type}|{text}".encode("utf-8")).hexdigest()


def get_client():
    from google import genai

    key = os.environ.get("GOOGLE_API_KEY")
    if not key:
        raise SystemExit("GOOGLE_API_KEY not set (put it in .env.local, which is git-ignored)")
    return genai.Client(api_key=key)


def embed_texts(client, texts: list[str], task_type: str | None, cache: dict) -> list[list[float]]:
    from google.genai import types

    out: list[list[float] | None] = [None] * len(texts)
    todo = [(i, t) for i, t in enumerate(texts) if cache_key(t, task_type) not in cache]
    for i, t in enumerate(texts):
        k = cache_key(t, task_type)
        if k in cache:
            out[i] = cache[k]
    done = 0
    for i, t in todo:
        cfg = types.EmbedContentConfig(output_dimensionality=DIMENSIONS, task_type=task_type) if task_type \
            else types.EmbedContentConfig(output_dimensionality=DIMENSIONS)
        for attempt in range(6):
            try:
                res = client.models.embed_content(model=MODEL, contents=[t], config=cfg)
                vec = list(res.embeddings[0].values)
                break
            except Exception as e:  # rate limit or transient error
                wait = 4 * 2 ** attempt
                print(f"  retry in {wait}s: {str(e)[:120]}", flush=True)
                time.sleep(wait)
        else:
            raise SystemExit("gave up after repeated API errors")
        cache[cache_key(t, task_type)] = vec
        out[i] = vec
        done += 1
        if done % 25 == 0:
            save_cache(cache)
            print(f"  {done}/{len(todo)} embedded", flush=True)
    save_cache(cache)
    return [v for v in out if v is not None]


# --- metrics ------------------------------------------------------------------

def metrics(M: np.ndarray, pool: list[dict]) -> dict:
    M = M / np.linalg.norm(M, axis=1, keepdims=True)
    n = len(pool)
    lab = [p["label"] for p in pool]
    src = [p["source"] for p in pool]
    gen = [p["generated"] is not None for p in pool]
    freq = Counter(lab)
    p_all = p_other = base_all = base_other = 0.0
    gen_match = gen_base = 0.0
    n_other = 0
    for k in range(n):
        sims = M @ M[k]
        sims[k] = -1
        order = np.argsort(-sims)
        top = order[:10]
        p_all += float(np.mean([lab[j] == lab[k] for j in top]))
        base_all += (freq[lab[k]] - 1) / (n - 1)
        same_src = [j for j in order if src[j] == src[k]][:10]
        if len(same_src) >= 5:
            gen_match += float(np.mean([gen[j] == gen[k] for j in same_src]))
            pool_src = [j for j in range(n) if src[j] == src[k] and j != k]
            gen_base += float(np.mean([gen[j] == gen[k] for j in pool_src]))
        other = [j for j in order if src[j] != src[k]][:10]
        if other:
            n_other += 1
            p_other += float(np.mean([lab[j] == lab[k] for j in other]))
            pool_o = [j for j in range(n) if src[j] != src[k]]
            base_other += sum(lab[j] == lab[k] for j in pool_o) / len(pool_o)
    n_gen = sum(1 for k in range(n) if len([j for j in range(n) if src[j] == src[k]]) - 1 >= 5)
    return {
        "P@10 technique": p_all / n, "chance": base_all / n,
        "P@10 technique, other sources": p_other / max(n_other, 1), "chance (other)": base_other / max(n_other, 1),
        "same-source neighbours sharing gen status": (gen_match / n_gen) if n_gen else float("nan"),
        "chance (gen)": (gen_base / n_gen) if n_gen else float("nan"),
    }


# --- main ---------------------------------------------------------------------

def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dry-run", action="store_true", help="print pool size and token estimate; no API calls")
    ap.add_argument("--variants", default=",".join(VARIANTS), help="comma-separated subset of: " + ", ".join(VARIANTS))
    ap.add_argument("--per-label", type=int, default=PER_LABEL)
    a = ap.parse_args()
    conn = sqlite3.connect(DB_PATH)
    pool = build_pool(conn, a.per_label)
    labels = Counter(p["label"] for p in pool)
    print(f"pool: {len(pool)} questions, {len(labels)} techniques x {a.per_label}, "
          f"{len(set(p['source'] for p in pool))} sources, {sum(p['generated'] is not None for p in pool)} with a generated solution")
    print("techniques:", ", ".join(sorted(labels)))
    names = [v.strip() for v in a.variants.split(",") if v.strip()]
    chars = {name: sum(len(VARIANTS[name][0](p)) for p in pool) for name in names}
    total_tokens = sum(chars.values()) / 3.5
    print(f"text to embed: {sum(chars.values()) / 1e6:.2f}M chars across {len(names)} variants ~ {total_tokens / 1e6:.2f}M tokens "
          f"(~{total_tokens / 1e6 * 0.20:.2f} USD at 0.20 USD per million; the 'current' variant reuses stored vectors when its text is unchanged)")
    if a.dry_run:
        return

    client = get_client()
    cache = load_cache()
    results = {}
    # Stored vectors as the zero-cost reference for the current prompt.
    stored = np.frombuffer(b"".join(p["stored"] for p in pool), dtype="<f4").reshape(len(pool), DIMENSIONS).astype(np.float32)
    results["stored (current prompt, June run)"] = metrics(stored, pool)
    for name in names:
        builder, task_type, note = VARIANTS[name]
        texts = [builder(p) for p in pool]
        print(f"\n== {name}: {note}", flush=True)
        try:
            vecs = embed_texts(client, texts, task_type, cache)
        except SystemExit:
            raise
        except Exception as e:
            print(f"   skipped: {str(e)[:200]}")
            continue
        results[name] = metrics(np.array(vecs, dtype=np.float32), pool)

    print("\n" + "=" * 110)
    cols = list(next(iter(results.values())).keys())
    print(f"{'variant':44s}" + "".join(f"{c[:22]:>24s}" for c in cols))
    for name, r in results.items():
        print(f"{name:44s}" + "".join(f"{r[c]:>24.2f}" for c in cols))
    out = Path("app/data/appdata/embed_ab_results.json")
    out.write_text(json.dumps({"pool": [(p["qid"], p["label"], p["source"]) for p in pool], "results": results}, indent=1), encoding="utf-8")
    print(f"\nwritten {out}")


if __name__ == "__main__":
    sys.exit(main())
