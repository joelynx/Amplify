"""
Gemini re-embedding of question + best available solution
---------------------------------------------------------
Embeds every question whose embedding is missing or stale and writes the
vector to `questions.similarity_emb` and `questions.classification_emb`
(the same vector in both, as the June 2026 run did).

What is embedded (keep byte-identical across runs; the A/B test of
2026-10-21 showed the prefix is as good as any alternative):

    Task: Find problems that share similar underlying concepts, solution techniques, and logical structures.

    Question:
    <latexcode>

    Solution:
    <generated_solution without its attribution line, else solution>

plus every image the question or solution references (multimodal; those
rows always go through the synchronous API).

Provenance (migration 006): `emb_text_hash` is the sha256 of the exact text
and image list that produced the stored vector, `emb_model` the model id. A
row is (re)embedded when its current text hashes differently, so the script
is incremental and resumable. On the first run, rows that never had a
generated solution and still carry the June vector (identical in both
columns) are back-filled with the hash of their current text.

Modes:
  --mode sync   one request per row, about 1 row/s, full price
  --mode batch  Batch API (half price): jobs of --batch-size text-only rows,
                polled until they finish; three rows per job are re-embedded
                synchronously to confirm the batch kept request order. Rows
                with images, failed jobs and failed items fall back to sync.
                Submitted job names are saved to reembed_jobs.json; if the
                script dies while polling, --resume-jobs collects them instead
                of paying for them again.

Usage (repo root, GOOGLE_API_KEY in .env.local):
  python -m app.tools.reembed --dry-run
  python -m app.tools.reembed --run [--mode sync|batch] [--limit N] [--batch-size 1000]
  python -m app.tools.reembed --run --mode batch --resume-jobs
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import mimetypes
import os
import re
import sqlite3
import struct
import sys
import time
from pathlib import Path

try:
    from dotenv import load_dotenv

    load_dotenv(".env.local")
except ImportError:
    pass

DB_PATH = Path("app/data/appdata/amplify.db")
IMG_DIR = Path("app/data/appdata/teximages")
JOBS_FILE = Path("app/data/appdata/reembed_jobs.json")

MODEL = "models/gemini-embedding-2"
MODEL_LABEL = "gemini-embedding-2"
DIMENSIONS = 3072
TASK_PREFIX = (
    "Task: Find problems that share similar underlying concepts, solution techniques, and logical structures.\n\n"
)
PRICE_PER_MTOK = 0.20  # USD, interactive; batch is half (aggregator figure)

IMG_PATTERN = re.compile(r"\\includegraphics\s*(?:\[[^\]]*\])?\s*\{([^}]+)\}")
ATTRIBUTION_RE = re.compile(r"\s*\\textit\{\[Generated by [^\]]*\]\}\s*$")
TERMINAL = {"JOB_STATE_SUCCEEDED", "JOB_STATE_FAILED", "JOB_STATE_CANCELLED", "JOB_STATE_EXPIRED"}


# --- text --------------------------------------------------------------------

def extract_images(latex: str | None) -> list[Path]:
    found: list[Path] = []
    for name in IMG_PATTERN.findall(latex or ""):
        base = name.strip()
        for p in (IMG_DIR / base, IMG_DIR / f"{base}.png", IMG_DIR / f"{base}.jpg", IMG_DIR / f"{base}.jpeg"):
            if p.exists() and p.is_file():
                if p not in found:
                    found.append(p)
                break
    return found


def best_solution(solution: str | None, generated: str | None) -> str:
    if generated and generated.strip():
        return ATTRIBUTION_RE.sub("", generated).strip()
    return solution or ""


def build_item(row: sqlite3.Row) -> dict:
    """Exactly what the June 2026 script sent: prefix + question (+ solution), then images."""
    q_latex = row["latexcode"] or ""
    s_latex = best_solution(row["solution"], row["generated_solution"])
    text = TASK_PREFIX + f"Question:\n{q_latex}"
    if s_latex.strip():
        text += f"\n\nSolution:\n{s_latex}"
    text = text.strip()
    images = extract_images(q_latex) + extract_images(s_latex)
    h = hashlib.sha256()
    h.update(MODEL.encode("utf-8"))
    h.update(b"|")
    h.update(text.encode("utf-8"))
    for p in images:
        h.update(b"|")
        h.update(p.name.encode("utf-8"))
    return {"qid": row["question_id"], "text": text, "images": images, "hash": h.hexdigest()}


# --- db ----------------------------------------------------------------------

ROW_SQL = (
    "SELECT question_id, latexcode, solution, generated_solution, emb_text_hash, "
    "similarity_emb IS NOT NULL AS has_vec, similarity_emb = classification_emb AS same_vec FROM questions"
)


def connect() -> sqlite3.Connection:
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row
    return conn


def ensure_schema(conn: sqlite3.Connection) -> None:
    """Apply pending app migrations (006 adds emb_text_hash / emb_model)."""
    cols = {r["name"] for r in conn.execute("PRAGMA table_info(questions)")}
    if "emb_text_hash" in cols and "emb_model" in cols:
        return
    sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
    from app.persistence.db import migrate

    applied = migrate(conn)
    print(f"applied migrations: {applied}", flush=True)


def plan(conn: sqlite3.Connection) -> tuple[list[dict], int]:
    """Back-fill hashes for rows whose stored vector still matches their text,
    then return the rows whose text is new or changed."""
    backfilled = 0
    pending: list[dict] = []
    for r in conn.execute(ROW_SQL + " ORDER BY question_id").fetchall():
        it = build_item(r)
        if r["emb_text_hash"] == it["hash"]:
            continue
        if r["emb_text_hash"] is None and r["has_vec"] and r["same_vec"] and not r["generated_solution"]:
            conn.execute(
                "UPDATE questions SET emb_text_hash = ?, emb_model = ? WHERE question_id = ?",
                (it["hash"], MODEL_LABEL, it["qid"]),
            )
            backfilled += 1
            continue
        pending.append(it)
    conn.commit()
    return pending, backfilled


def items_for(conn: sqlite3.Connection, qids: list[int]) -> list[dict]:
    by_qid = {}
    for i in range(0, len(qids), 900):
        chunk = qids[i : i + 900]
        marks = ",".join("?" * len(chunk))
        for r in conn.execute(ROW_SQL + f" WHERE question_id IN ({marks})", chunk):
            by_qid[r["question_id"]] = build_item(r)
    return [by_qid[q] for q in qids]


def store(conn: sqlite3.Connection, item: dict, vec: list[float]) -> None:
    if len(vec) != DIMENSIONS:
        raise ValueError(f"q{item['qid']}: got {len(vec)} dims")
    blob = struct.pack(f"<{DIMENSIONS}f", *vec)
    conn.execute(
        "UPDATE questions SET classification_emb = ?, similarity_emb = ?, emb_text_hash = ?, emb_model = ? "
        "WHERE question_id = ?",
        (blob, blob, item["hash"], MODEL_LABEL, item["qid"]),
    )


def set_model_config(conn: sqlite3.Connection) -> None:
    try:
        conn.execute("UPDATE configs SET value = ? WHERE key = 'EMBED_MODEL_VERSION'", (json.dumps(MODEL_LABEL),))
        conn.commit()
    except sqlite3.Error as e:
        print(f"note: could not update EMBED_MODEL_VERSION ({e})")


# --- API ---------------------------------------------------------------------

def get_client():
    from google import genai

    key = os.environ.get("GOOGLE_API_KEY")
    if not key:
        raise SystemExit("GOOGLE_API_KEY not set (put it in .env.local; that file is git-ignored)")
    return genai.Client(api_key=key)


def embed_one(client, item: dict) -> list[float]:
    from google.genai import types

    parts: list = [item["text"]]
    for p in item["images"]:
        try:
            mime, _ = mimetypes.guess_type(str(p))
            parts.append(types.Part.from_bytes(data=p.read_bytes(), mime_type=mime or "image/png"))
        except Exception as e:
            print(f"  q{item['qid']}: could not read image {p}: {e}", flush=True)
    for attempt in range(8):
        try:
            res = client.models.embed_content(
                model=MODEL, contents=parts, config=types.EmbedContentConfig(output_dimensionality=DIMENSIONS)
            )
            return list(res.embeddings[0].values)
        except Exception as e:
            wait = min(4 * 2**attempt, 120)
            print(f"  q{item['qid']}: {str(e)[:160]} -> retry in {wait}s", flush=True)
            time.sleep(wait)
    raise RuntimeError(f"q{item['qid']}: gave up after repeated errors")


def cosine(a: list[float], b: list[float]) -> float:
    dot = sum(x * y for x, y in zip(a, b))
    na = math.sqrt(sum(x * x for x in a))
    nb = math.sqrt(sum(x * x for x in b))
    return dot / (na * nb) if na and nb else 0.0


def run_sync(conn: sqlite3.Connection, client, pending: list[dict]) -> int:
    t0 = time.time()
    done = 0
    for i, item in enumerate(pending, 1):
        try:
            store(conn, item, embed_one(client, item))
            done += 1
        except Exception as e:
            print(f"[{i}/{len(pending)}] FAILED q{item['qid']}: {e}", flush=True)
            continue
        if i % 20 == 0 or i == len(pending):
            conn.commit()
            rate = i / (time.time() - t0)
            eta = (len(pending) - i) / rate
            print(f"[{i}/{len(pending)}] saved | {rate:.2f} rows/s | ETA {int(eta // 60)}m {int(eta % 60)}s", flush=True)
    conn.commit()
    return done


def submit_batch(client, items: list[dict], label: str):
    from google.genai import types

    src = types.EmbeddingsBatchJobSource(
        inlined_requests=types.EmbedContentBatch(
            contents=[it["text"] for it in items],
            config=types.EmbedContentConfig(output_dimensionality=DIMENSIONS),
        )
    )
    return client.batches.create_embeddings(
        model=MODEL, src=src, config=types.CreateEmbeddingsBatchJobConfig(display_name=label)
    )


def batch_vectors(job) -> list[list[float] | None]:
    """One vector per request, in request order (None for a failed item)."""
    out: list[list[float] | None] = []
    for r in job.dest.inlined_embed_content_responses or []:
        resp = r.response
        if r.error or resp is None:
            out.append(None)
            continue
        embs = getattr(resp, "embeddings", None)
        if embs:
            out.extend(list(e.values) for e in embs)
        elif getattr(resp, "embedding", None) is not None:
            out.append(list(resp.embedding.values))
        else:
            out.append(None)
    return out


def order_ok(client, chunk: list[dict], vecs: list[list[float] | None]) -> bool:
    """Re-embed three rows synchronously; the batch vector must match (cosine > 0.99)."""
    for i in sorted({0, len(chunk) // 2, len(chunk) - 1}):
        if vecs[i] is None:
            continue
        c = cosine(embed_one(client, chunk[i]), vecs[i])
        if c < 0.99:
            print(f"  order check failed at index {i} (q{chunk[i]['qid']}): cosine {c:.4f}", flush=True)
            return False
    return True


def save_jobs(jobs: dict[str, list[dict]]) -> None:
    JOBS_FILE.write_text(json.dumps({name: [it["qid"] for it in chunk] for name, chunk in jobs.items()}), encoding="utf-8")


def run_batch(conn: sqlite3.Connection, client, pending: list[dict], batch_size: int, resume: bool, poll: int = 30) -> int:
    """Submit chunks as the service accepts them (a refused submission is retried
    every poll interval for up to 20 min, then goes through sync), poll the
    running jobs and store their vectors as each one finishes."""
    fallback: list[dict] = []
    remaining: dict[str, list[dict]] = {}
    queue: list[tuple[int, list[dict]]] = []
    if resume:
        saved = json.loads(JOBS_FILE.read_text(encoding="utf-8"))
        for name, qids in saved.items():
            remaining[name] = items_for(conn, qids)
        covered = {it["qid"] for chunk in remaining.values() for it in chunk}
        pending = [it for it in pending if it["qid"] not in covered]
        print(f"resuming {len(remaining)} saved jobs ({len(covered)} rows); {len(pending)} pending rows are in no job yet", flush=True)
    fallback = [it for it in pending if it["images"]]
    text_only = [it for it in pending if not it["images"]]
    queue = [(str(n), text_only[i : i + batch_size]) for n, i in enumerate(range(0, len(text_only), batch_size), 1)]
    n_chunks = len(queue)
    # The service refuses a job above an undocumented size (2026-10-21: 250 rows
    # / 1.4 MB accepted, 500 rows refused with a bare 429) and, presumably, past
    # some number of jobs in flight. A refusal while jobs are running is treated
    # as the latter (wait for one to finish); with nothing running the chunk is
    # halved down to 50 rows, then retried a few times, then sent through sync.
    attempts: dict[str, int] = {}
    waits = 0
    done = 0
    t0 = time.time()
    states: dict[str, str] = {}
    while remaining or queue:
        while queue:
            n, chunk = queue[0]
            try:
                job = submit_batch(client, chunk, f"amplify-reembed-{n}")
            except Exception as e:
                msg = str(e).replace("\n", " ")[:300]
                if remaining:
                    waits += 1
                    if waits in (1, 10, 40):
                        print(f"  chunk {n} refused with {len(remaining)} jobs in flight; waiting ({msg})", flush=True)
                    break
                if len(chunk) > 50:
                    half = len(chunk) // 2
                    queue[0:1] = [(n + "a", chunk[:half]), (n + "b", chunk[half:])]
                    print(f"  chunk {n} ({len(chunk)} rows) refused with nothing in flight; split in two ({msg})", flush=True)
                    continue
                attempts[n] = attempts.get(n, 0) + 1
                if attempts[n] >= 10:
                    print(f"chunk {n} refused {attempts[n]} times; its {len(chunk)} rows go through sync", flush=True)
                    fallback.extend(chunk)
                    queue.pop(0)
                    continue
                print(f"  chunk {n} ({len(chunk)} rows) refused (attempt {attempts[n]}): {msg}", flush=True)
                break
            waits = 0
            queue.pop(0)
            remaining[job.name] = chunk
            save_jobs(remaining)
            size_mb = sum(len(it["text"]) for it in chunk) / 1e6
            print(f"submitted job {n} of ~{n_chunks}: {job.name} ({len(chunk)} rows, {size_mb:.1f} MB); {len(queue)} chunks queued", flush=True)
        if not remaining and not queue:
            break
        time.sleep(poll)
        for name in list(remaining):
            time.sleep(0.25)
            try:
                job = client.batches.get(name=name)
            except Exception as e:
                print(f"  poll {name}: {str(e)[:160]}", flush=True)
                continue
            if states.get(name) != job.state.name:
                states[name] = job.state.name
                print(f"  {int(time.time() - t0)}s {name}: {job.state.name}", flush=True)
            if job.state.name not in TERMINAL:
                continue
            chunk = remaining.pop(name)
            if job.state.name != "JOB_STATE_SUCCEEDED":
                print(f"job {name} ended {job.state.name}; its {len(chunk)} rows go through sync", flush=True)
                fallback.extend(chunk)
                save_jobs(remaining)
                continue
            vecs = batch_vectors(job)
            if len(vecs) != len(chunk) or not order_ok(client, chunk, vecs):
                print(f"job {name}: {len(vecs)} vectors for {len(chunk)} rows, or order mismatch; sync for this job", flush=True)
                fallback.extend(chunk)
                save_jobs(remaining)
                continue
            n_fail = 0
            for it, v in zip(chunk, vecs):
                if v is None:
                    fallback.append(it)
                    n_fail += 1
                    continue
                store(conn, it, v)
                done += 1
            conn.commit()
            save_jobs(remaining)
            print(
                f"job {name} stored ({n_fail} items failed): {done} rows so far, {len(remaining)} jobs left ({int(time.time() - t0)}s)",
                flush=True,
            )
    if fallback:
        print(f"{len(fallback)} rows through the synchronous API (images, failed jobs or failed items)", flush=True)
        done += run_sync(conn, client, fallback)
    return done


# --- main --------------------------------------------------------------------

def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--run", action="store_true", help="embed the pending rows")
    ap.add_argument("--dry-run", action="store_true", help="report what would be embedded and the cost; no API calls")
    ap.add_argument("--mode", choices=["sync", "batch"], default="sync")
    ap.add_argument("--limit", type=int, help="embed at most N rows (lowest question_id first)")
    ap.add_argument("--batch-size", type=int, default=250, help="rows per batch job (500 was refused on 2026-10-21)")
    ap.add_argument("--resume-jobs", action="store_true", help="collect the jobs listed in reembed_jobs.json instead of submitting")
    a = ap.parse_args()
    if not (a.run or a.dry_run):
        ap.print_help()
        return
    conn = connect()
    ensure_schema(conn)
    pending, backfilled = plan(conn)
    if a.limit:
        pending = pending[: a.limit]
    chars = sum(len(it["text"]) for it in pending)
    tokens = chars / 3.5
    n_img = sum(1 for it in pending if it["images"])
    print(
        f"back-filled hashes for {backfilled} rows | pending {len(pending)} rows ({n_img} with images) | "
        f"{chars / 1e6:.1f}M chars ~ {tokens / 1e6:.1f}M tokens ~ {tokens / 1e6 * PRICE_PER_MTOK:.2f} USD sync, "
        f"{tokens / 1e6 * PRICE_PER_MTOK / 2:.2f} USD batch (at {PRICE_PER_MTOK} USD per million)",
        flush=True,
    )
    if a.dry_run or not pending:
        return
    client = get_client()
    t0 = time.time()
    if a.mode == "batch":
        done = run_batch(conn, client, pending, a.batch_size, a.resume_jobs)
    else:
        done = run_sync(conn, client, pending)
    set_model_config(conn)
    left = conn.execute("SELECT COUNT(*) FROM questions WHERE similarity_emb IS NULL").fetchone()[0]
    stale = conn.execute("SELECT COUNT(*) FROM questions WHERE emb_text_hash IS NULL").fetchone()[0]
    print(
        f"done: {done}/{len(pending)} rows embedded in {int((time.time() - t0) / 60)} min; "
        f"rows without a vector: {left}; rows without a provenance hash: {stale}",
        flush=True,
    )


if __name__ == "__main__":
    main()
