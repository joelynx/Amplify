"""Assemble and store the final solution for every passed question.

For each question with a passing status that has not been assembled yet:
  1. extract solution / rigor notes / takeaways / answer / hint from the
     accepted solver reply (solver_<attempt>.tex), dropping all %%% marker
     lines. Legacy v4 replies take rigor notes from the review file and the
     hint from hint.tex instead;
  2. build final.tex in the layout from format_spec.md:
         <solution>
         \\medskip\\noindent\\textbf{Rigor Notes}      (omitted when none)
         <rigor notes>
         \\medskip\\noindent\\textbf{Takeaways}
         <takeaways>
         \\hfill [Generated by <model> at <effort> effort]
  3. convert the answer to the Answer-field format (code only, never a model);
  4. run the PDF and web checks on the assembled solution, answer, and hint,
     and compile preview.pdf (question + solution) for spot-checks;
  5. store everything in pipeline.db (finals + provenance) and write
     final_app.json with the app's column layout;
  6. queue the generated_solution column write and the empty Answer / Hint
     fills (apply_fields.py writes them to the app database).

Usage: python assemble.py [qid ...]   (default: every passed, unassembled question)
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from apply_fields import apply_pending  # noqa: E402
from check_pdf import check_pdf  # noqa: E402
from common import (  # noqa: E402
    PASS_STATUSES,
    app_conn,
    check_web_parts,
    fetch_question,
    format_answer,
    get_status,
    is_blank,
    load_config,
    log_event,
    model_display,
    now_iso,
    parse_solver_output,
    pipe_conn,
    pipeline_wrote,
    q_dir,
    read_text,
    repair_slips,
    strip_code_fences,
    strip_marker_lines,
    upsert_status,
    write_json,
    write_progress,
    write_text,
)


def title(t: str) -> str:
    return f"\\medskip\\noindent\\textbf{{{t}}}"


def build_final(solution: str, rigor: str | None, takeaways: str) -> str:
    parts = [solution.strip()]
    if rigor:
        parts += [title("Rigor Notes"), rigor.strip()]
    parts += [title("Takeaways"), takeaways.strip()]
    return "\n\n".join(parts) + "\n"


def accepted_parts(row, d: Path) -> tuple[dict | None, list[str], str | None, str | None]:
    """(parts, errors, rigor, hint) from the accepted attempt."""
    acc = int(row["accepted_attempt"])
    text, _ = repair_slips(strip_code_fences(read_text(d / f"solver_{acc}.tex"))[0])
    parts, errs = parse_solver_output(text)
    if parts is None:
        return None, errs, None, None
    if parts["format"] == "v5":
        rigor = parts["rigor"]
        hint = parts["hint"] if row["hint_status"] == "ok" else None
    else:  # legacy subagent-era outputs
        rp = d / f"review_{acc}_rigor.tex"
        rigor_raw = read_text(rp).strip() if rp.exists() else "%%% NONE"
        rigor = None if rigor_raw == "%%% NONE" else strip_marker_lines(rigor_raw)
        hint = None
        if row["hint_status"] == "ok" and (d / "hint.tex").exists():
            lines = read_text(d / "hint.tex").strip().split("\n")
            hint = "\n".join(lines[1:]).strip() or None
    return parts, [], rigor, hint


def assemble_one(qid: int, cfg: dict, app, pc) -> dict:
    row = get_status(pc, qid)
    q = fetch_question(app, qid)
    d = q_dir(qid)
    acc = int(row["accepted_attempt"])
    parts, errs, rigor, hint = accepted_parts(row, d)
    if parts is None:
        return {"question_id": qid, "ok": False, "errors": errs}
    solution = strip_marker_lines(parts["solution"])
    takeaways = strip_marker_lines(parts["takeaways"])
    # Owner decision (2026-10-18): every stored solution ends with an
    # attribution line naming the model and effort that produced it, in the
    # same \hfill [Generated by ...] form as the Gemini solutions (2026-11-03).
    acc_model = row["solver2_model"] if acc >= 2 else row["solver1_model"]
    acc_effort = row["solver2_effort"] if acc >= 2 else row["solver1_effort"]
    attribution = f"\\hfill [Generated by {model_display(cfg, acc_model)} at {acc_effort} effort]"
    final = build_final(solution, rigor, takeaways) + "\n" + attribution + "\n"

    answer_value = format_answer(parts["answer_type"], parts["answer"])

    errors: list[str] = []
    r = check_pdf(final, cfg=cfg)
    errors += [f"pdf[final]: {e}" for e in r["errors"]]
    pieces = {"final": final}
    if answer_value:
        pieces["answer"] = answer_value
        r = check_pdf(answer_value, cfg=cfg)
        errors += [f"pdf[answer]: {e}" for e in r["errors"]]
    if hint:
        pieces["hint"] = hint
        r = check_pdf(hint, cfg=cfg)
        errors += [f"pdf[hint]: {e}" for e in r["errors"]]
    w = check_web_parts(pieces, d)
    errors += [f"web{e}" for e in w["errors"]]
    if errors:
        write_json(d / "assemble_errors.json", {"errors": errors, "at": now_iso()})
        upsert_status(pc, qid, status="needs_human_review", note="assembled content failed checks: " + "; ".join(errors)[:300])
        log_event(pc, qid, "assemble", "FAILED: " + "; ".join(errors)[:300])
        return {"question_id": qid, "ok": False, "errors": errors}

    preview = d / "preview.pdf"
    if cfg.get("preview_pdf", True):
        pv = check_pdf(final, question_tex=q["latexcode"], pdf_out=preview, cfg=cfg)
        preview_note = "with question"
        if not pv["ok"]:
            pv = check_pdf(final, pdf_out=preview, cfg=cfg)
            preview_note = "solution only (question text itself failed to compile)" if pv["ok"] else "preview failed: " + "; ".join(pv["errors"])[:200]
    else:
        preview_note = "skipped (config preview_pdf false)"

    write_text(d / "final.tex", final)
    sentinels = cfg["empty_answer_sentinels"]
    # A value an earlier pipeline run wrote counts as empty: a redo replaces it.
    ans_empty = is_blank(q["answer"], sentinels) or pipeline_wrote(pc, qid, "answer", q["answer"])
    hint_empty = is_blank(q["hints"]) or pipeline_wrote(pc, qid, "hints", q["hints"])
    fill_answer = answer_value if (ans_empty and parts["answer_type"] != "NONE" and row["status"] in ("passed", "passed_after_escalation")) else None
    # An accepted review solve that disagrees with the stored answer replaces it (owner 2026-11-11,
    # as for the subjects); apply_fields keeps the old value as answer_before_replace.
    reviewed = "review_from" in row.keys() and row["review_from"]
    replace_answer = (answer_value if (reviewed and row["answer_mismatch"] and parts["answer_type"] != "NONE"
                                       and row["status"] == "passed") else None)
    if replace_answer:
        fill_answer = None
    fill_hint = hint if (hint_empty and hint) else None
    gen_col = cfg.get("generated_solution_column") or "generated_solution"
    app_record = {
        "question_id": qid,
        gen_col: final,
        "answer": fill_answer,
        **({"answer_replace": replace_answer} if replace_answer else {}),
        "hints": fill_hint,
        "answer_type": parts["answer_type"],
        "answer_value": answer_value,
        "status": row["status"],
        "accepted_attempt": acc,
        "model": acc_model,
        "effort": acc_effort,
        "prompt_version": cfg["prompt_version"],
        "preview": preview_note,
    }
    write_json(d / "final_app.json", app_record)

    pc.execute(
        """INSERT OR REPLACE INTO finals
           (question_id, status, final_tex, solution_tex, rigor_tex, takeaways_tex, answer_type, answer_tex,
            hint_tex, answer_field_value, hint_field_value, answer_filled, hint_filled, prompt_version, created_at)
           VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)""",
        (qid, row["status"], final, solution, rigor, takeaways, parts["answer_type"], parts["answer"],
         hint, fill_answer or replace_answer, fill_hint, 0, 0, cfg["prompt_version"], now_iso()),
    )
    for field, value in ((gen_col, final), ("answer", fill_answer), ("answer_replace", replace_answer), ("hints", fill_hint)):
        if value is None:
            continue
        exists = pc.execute(
            "SELECT 1 FROM provenance WHERE question_id=? AND field=? AND applied_at IS NULL", (qid, field)
        ).fetchone()
        if not exists:
            pc.execute(
                "INSERT INTO provenance (question_id, field, value, prompt_version, created_at) VALUES (?,?,?,?,?)",
                (qid, field, value, cfg["prompt_version"], now_iso()),
            )
    pc.commit()
    upsert_status(pc, qid, assembled=1)
    log_event(pc, qid, "assemble", f"ok; preview {preview_note}; fills answer={fill_answer is not None} hint={fill_hint is not None}"
              + ("; replaces the stored answer" if replace_answer else ""))
    return {
        "question_id": qid,
        "ok": True,
        "status": row["status"],
        "answer_type": parts["answer_type"],
        "answer_field": fill_answer,
        "hint_field": (fill_hint[:80] + "...") if fill_hint and len(fill_hint) > 80 else fill_hint,
        "final_chars": len(final),
        "preview": preview.as_posix() if preview.exists() else None,
        "preview_note": preview_note,
    }


def main() -> None:
    cfg = load_config()
    app = app_conn(cfg)
    pc = pipe_conn()
    ids = [int(x) for x in sys.argv[1:]]
    if not ids:
        for row in pc.execute("SELECT * FROM status ORDER BY question_id"):
            if row["status"] in PASS_STATUSES and not row["assembled"] and row["hint_status"] in ("ok", "failed", "skipped"):
                ids.append(row["question_id"])
    for qid in ids:
        print(json.dumps(assemble_one(qid, cfg, app, pc)))
    if ids:
        applied = apply_pending(cfg, pc)
        print(json.dumps({"field_fills": applied}))
    else:
        print("(nothing to assemble)")
    write_progress(pc)


if __name__ == "__main__":
    main()
