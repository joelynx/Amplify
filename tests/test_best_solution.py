"""The generated (Claude) solution is shown wherever the app shows one solution:
PDFs, quizzes, and the Browser (which also gets the source's own solution)."""

from __future__ import annotations

import sqlite3

from app.core.models import Question
from app.ipc.api import Api, _question_full_dict
from app.persistence.repositories import questions as questions_repo
from app.tex.solutions import render_solution_block

GEN = "Generated proof.\n\n\\hfill [Generated by Claude Opus 5.5 at medium effort]\n"


def _q(**kw) -> Question:
    base = dict(question_id=1, topic="T", branch="B", subtopic="S", latexcode="x", latex_hash="h",
                in_syllabus=1, times_used=0, interactive_times_used=0)
    return Question(**{**base, **kw})


def test_best_solution_prefers_generated():
    assert _q(solution="orig", generated_solution=GEN).best_solution() == GEN
    assert _q(generated_solution=GEN).best_solution() == GEN
    assert _q(solution="orig").best_solution() == "orig"
    assert _q(solution="orig", generated_solution="  \n").best_solution() == "orig"
    assert _q().best_solution() is None


def test_repo_and_api_carry_both_solutions(seeded_conn: sqlite3.Connection):
    seeded_conn.execute(
        "UPDATE questions SET solution = 'orig', generated_solution = ? WHERE question_id = 1", (GEN,)
    )
    q = questions_repo.get_by_id(seeded_conn, 1)
    assert (q.solution, q.generated_solution) == ("orig", GEN)
    d = Api(lambda: seeded_conn).get_question(1)
    assert (d["solution"], d["generated_solution"]) == ("orig", GEN)


def test_pdf_solution_block_uses_generated():
    q = _q(solution="orig", generated_solution=GEN)
    assert render_solution_block(q, 3, use_outline=False) == "\\noindent\\textbf{Q3.}~" + GEN
    # Outline modes fall back to the full (generated) solution when there is no outline.
    assert render_solution_block(q, 3, use_outline=True) == "\\noindent\\textbf{Q3.}~" + GEN
    with_outline = _q(solution="orig", generated_solution=GEN, solution_outline="outline")
    assert render_solution_block(with_outline, 1, use_outline=True) == "\\noindent\\textbf{Q1.}~outline"


def test_quiz_question_dict_uses_generated():
    assert _question_full_dict(_q(solution="orig", generated_solution=GEN))["solution"] == GEN
    assert _question_full_dict(_q(solution="orig"))["solution"] == "orig"
